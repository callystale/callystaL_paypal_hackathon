"use client";

import { useState } from "react";
import { api, type MilestoneDTO, type PlanResponse, type StatusDTO, type SummaryDTO } from "@/lib/client";
import { EmptyState, Money, PriorityBadge, Spinner } from "./ui";

export function PlanPanel({
  plan,
  status,
  summary,
  run,
  onCheckout,
}: {
  plan: PlanResponse | null;
  status: StatusDTO | null;
  summary: SummaryDTO | null;
  run: (fn: () => Promise<unknown>) => Promise<void>;
  onCheckout: (milestone: MilestoneDTO) => void;
}) {
  const [generating, setGenerating] = useState(false);
  const currencyCode = summary?.currency ?? "USD";
  const milestones = plan?.milestones ?? [];

  const generate = async () => {
    setGenerating(true);
    await run(() => api.post("/api/plan"));
    setGenerating(false);
  };

  return (
    <section className="card">
      <header className="mb-4 flex flex-wrap items-center justify-between gap-3">
        <div>
          <p className="text-xs font-semibold uppercase tracking-wide text-brand-400">
            Step 5 · Staged plan
          </p>
          <h2 className="text-lg font-semibold">AI milestones</h2>
          {plan && (
            <p className="text-xs text-slate-400">
              Affordable budget per milestone:{" "}
              <Money amount={plan.monthlyBudget} currency={currencyCode} />
              {plan.source ? (
                <>
                  {" · "}
                  {plan.source === "ollama" ? (
                    <span className="text-emerald-400">
                      generated by {status?.ollama.model ?? "local model"}
                    </span>
                  ) : (
                    <span className="text-amber-400">heuristic fallback (Ollama unavailable)</span>
                  )}
                </>
              ) : null}
            </p>
          )}
        </div>
        <div className="flex gap-2">
          <button className="btn-secondary" onClick={generate} disabled={generating}>
            {generating ? <Spinner /> : null}
            {milestones.length ? "Regenerate" : "Generate plan"}
          </button>
          {milestones.length > 0 && (
            <button className="btn-ghost" onClick={() => run(() => api.delete("/api/plan"))}>
              Clear
            </button>
          )}
        </div>
      </header>

      {milestones.length === 0 ? (
        <EmptyState>
          Add items to your wishlist, then generate a staged plan. The AI groups them into
          milestones you can afford, respecting priority and target dates.
        </EmptyState>
      ) : (
        <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
          {milestones.map((m) => (
            <article
              key={m.id}
              className="flex flex-col rounded-xl border border-slate-700 bg-slate-800/50 p-4"
            >
              <div className="mb-2 flex items-center justify-between">
                <h3 className="text-sm font-semibold">
                  <span className="mr-1.5 inline-flex h-5 w-5 items-center justify-center rounded-full bg-brand-600 text-[11px] text-white">
                    {m.sequence}
                  </span>
                  {m.title}
                </h3>
                <span className="text-sm font-semibold">
                  <Money amount={m.total} currency={currencyCode} />
                </span>
              </div>
              {m.rationale && <p className="mb-3 text-xs text-slate-400">{m.rationale}</p>}
              <ul className="mb-3 flex-1 space-y-1.5">
                {m.items.map((item) => (
                  <li key={item.id} className="flex items-center justify-between gap-2 text-sm">
                    <span className="flex items-center gap-1.5 truncate">
                      <PriorityBadge priority={item.priority} />
                      <span className="truncate">{item.alternativeName ?? item.name}</span>
                    </span>
                    <span className="text-slate-400">
                      <Money amount={item.effectivePrice} currency={currencyCode} />
                    </span>
                  </li>
                ))}
              </ul>
              <button
                className="btn-primary w-full"
                onClick={() => onCheckout(m)}
                disabled={m.status === "COMPLETED"}
              >
                {m.status === "COMPLETED" ? "Paid ✓" : "Check out this milestone"}
              </button>
            </article>
          ))}
        </div>
      )}
    </section>
  );
}
